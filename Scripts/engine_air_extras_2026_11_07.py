REWRITE = ["app/src/rendering/renderer.c", "app/src/game/ui_overlay.c"]


def rewrite_table(text):
    out, i = [], 0
    key = "BACKGROUNDS["
    while True:
        j = text.find(key, i)
        if j < 0:
            out.append(text[i:])
            return "".join(out)
        depth, k = 1, j + len(key)
        while depth:
            depth += {"[": 1, "]": -1}.get(text[k], 0)
            k += 1
        out.append(text[i:j] + "(*background_at(" + text[j + len(key):k - 1] + "))")
        i = k


