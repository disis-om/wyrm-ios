def _read(path):
    data = path.read_bytes().decode("utf-8")
    nl = "\r\n" if "\r\n" in data else "\n"
    return data, nl


def apply(root, dry=False):
    root = Path(root)
    pending = []
    for relative, changes in PAIRS.items():
        path = root / relative
        text, nl = _read(path)
        for old, new in changes:
            o, n = old.replace("\n", nl), new.replace("\n", nl)
            if text.count(n) == 1:
                continue  # already applied
            if text.count(o) != 1:
                raise SystemExit("air extras: anchor %d in %s: %s" % (text.count(o), relative, old[:70]))
            text = text.replace(o, n, 1)
        text = apply_multi(text, relative, nl)
        pending.append((path, text))
    for relative in REWRITE:
        path = root / relative
        for index, (pending_path, pending_text) in enumerate(pending):
            if pending_path == path:
                pending[index] = (path, rewrite_table(pending_text))
                break
        else:
            text, _nl = _read(path)
            pending.append((path, rewrite_table(text)))
    if dry:
        return
    for path, text in pending:
        path.write_bytes(text.encode("utf-8"))
    for relative in FILES:
        target = root / relative
        source = FILES_DIR / Path(relative).name
        if source.resolve() != target.resolve():
            shutil.copyfile(source, target)
    png = root / "app/res/textures/wyrm_extras.png"
    if PNG.resolve() != png.resolve():
        png.parent.mkdir(parents=True, exist_ok=True)
        shutil.copyfile(PNG, png)
        shutil.copyfile(PNG.with_suffix(".json"), png.with_suffix(".json"))
    sounds = root / "app/res/sounds"
    if SOUNDS.resolve() != sounds.resolve() and SOUNDS.exists():
        if sounds.exists():
            shutil.rmtree(sounds)
        shutil.copytree(SOUNDS, sounds)
    print("AIR extras: %d anchors, %d files" % (sum(map(len, PAIRS.values())), len(FILES)))


def revert(root):
    root = Path(root)
    for relative, changes in PAIRS.items():
        path = root / relative
        if not path.exists():
            continue
        text, nl = _read(path)
        for old, new in reversed(changes):
            o, n = old.replace("\n", nl), new.replace("\n", nl)
            if text.count(n) == 1:
                text = text.replace(n, o, 1)
        for old_m, new_m, _count in MULTI.get(relative, []):
            text = text.replace(new_m.replace("\n", nl), old_m.replace("\n", nl))
        path.write_bytes(text.encode("utf-8"))
    print("AIR extras reverted (new files left in place)")


