def apply(root, dry=False):
    pairs = PAIRS
    pending = []
    for file, changes in pairs.items():
        path = Path(root) / file
        text = path.read_text(encoding='utf-8')
        # Dry-run accepts fresh or applied trees; reconstruct the predecessor
        # in memory, then prove every original anchor occurs exactly once.
        if dry:
            trial = text
            for old, new in changes:
                if trial.count(old) != 1:
                    for before, after in reversed(changes):
                        if text.count(after) != 1:
                            raise SystemExit(f'overlay text: {file}: invalid applied anchor {after[:70]!r}')
                        text = text.replace(after, before, 1)
                    break
                trial = trial.replace(old, new, 1)
        for old, new in changes:
            count = text.count(old)
            if count != 1:
                raise SystemExit(f'overlay text: {file}: {count} anchors: {old[:90]!r}')
            text = text.replace(old, new, 1)
        pending.append((path, text))
    if not dry:
        for path, text in pending:
            path.write_text(text, encoding='utf-8')
    print(f'overlay text: {sum(map(len, pairs.values()))} single anchors / {len(pairs)} files; dry={dry}')


if __name__ == '__main__':
    apply(sys.argv[1], '--dry' in sys.argv)
