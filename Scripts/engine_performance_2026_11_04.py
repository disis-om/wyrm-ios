def apply(root, dry=False):
    root = Path(root)
    pending = []
    for relative, changes in PAIRS.items():
        path = root / relative
        text = path.read_text(encoding="utf-8")
        if dry and all(text.count(new) == 1 for old, new in changes):
            for old, new in reversed(changes):
                text = text.replace(new, old, 1)
        for old, new in changes:
            if text.count(old) != 1:
                raise AssertionError((relative, "performance anchor", text.count(old), old[:100]))
            text = text.replace(old, new, 1)
        pending.append((path, text))
    if not dry:
        for path, text in pending:
            path.write_text(text, encoding="utf-8")
        for relative, text in FILES.items():
            path = root / relative
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text, encoding="utf-8")
    else:
        for relative, text in FILES.items():
            assert (root / relative).read_text(encoding="utf-8") == text, relative
    print("Performance parity: %d anchors, %d helpers; dry=%s" %
          (sum(map(len, PAIRS.values())), len(FILES), dry))

if __name__ == "__main__":
    import sys
    apply(sys.argv[1], "--dry" in sys.argv)
